#!/usr/bin/env python3
"""Writes gstreamer/meson.build: configures the GStreamer subprojects with every optional
feature disabled except the few mirai's sounds need (GTK's media backend plays an in-memory
WAV through playbin). Usage: gen-options.py <dir with the four unpacked 1.28 tarballs>"""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1])
V = '1.28.7'
keep = {
    'gstreamer': {},
    'gst-plugins-base': {'gl': 'enabled', 'audioconvert': 'enabled', 'audioresample': 'enabled',
                         'playback': 'enabled', 'typefind': 'enabled', 'volume': 'enabled',
                         'gio': 'enabled',  # giostreamsrc: GtkMediaFile's input streams
                         'gl_api': "['gles2']", 'gl_platform': "['egl']", 'gl_winsys': "['android']"},
    'gst-plugins-good': {'autodetect': 'enabled', 'wavparse': 'enabled'},
    'gst-plugins-bad': {'opensles': 'enabled'},
}
out = ['# Generated by gen-options.py; do not edit.',
       '# GStreamer for GTK\'s media backend (GtkMediaFile), configured before GTK so that its',
       '# gstreamer-play/-gl/-allocators lookups find these. Every optional feature is off except',
       '# what playing mirai\'s WAV clips needs; the plugins are shared libraries that main.c',
       '# loads by name and registers (an APK has no plugin directory to scan).', '']
for mod, k in keep.items():
    text = (src / f'{mod}-{V}' / 'meson.options').read_text()
    opts = []
    for name, typ in re.findall(r"option\(\s*'([^']+)'\s*,\s*type\s*:\s*'(\w+)'", text):
        if name in k:
            v = k[name]
            opts.append(f"'{name}={v}'" if not v.startswith('[') else f"'{name}=' + ','.join({v})")
        elif typ == 'feature':
            opts.append(f"'{name}=disabled'")
    var = mod.replace('-', '_')
    out.append(f"{var}_proj = subproject('{mod}', default_options: [")
    out += [f'  {o},' for o in opts]
    out.append('])')
    out.append('')
out.append("gst_dep = dependency('gstreamer-1.0')")
(pathlib.Path(__file__).parent / 'meson.build').write_text('\n'.join(out) + '\n')

#!/bin/sh
# Copies the Adwaita symbolic icons mirai references into android/icons/ and writes
# android/icons.gresource.xml. Android has no icon theme, so these are compiled into
# libmirai.so under mirai's own icon resource path (see meson.build).
# Usage: update-icons.sh <adwaita-icon-theme checkout>   (tested with 49.0)
set -eu
src=$1
here=$(cd "$(dirname "$0")" && pwd)
names=$(rg -o --no-filename -g '*.rs' -g '*.blp' -g '*.ui' '"[a-z][a-z0-9-]*-symbolic"' "$here/../crates" |
        tr -d '"' | grep -v '^mirai-' | sort -u)
rm -rf "$here/icons"; mkdir -p "$here/icons"
{
  echo '<?xml version="1.0" encoding="UTF-8"?>'
  echo '<!-- Generated by update-icons.sh from adwaita-icon-theme (CC-BY-SA-3.0 / LGPL-3.0). -->'
  echo '<gresources>'
  echo '  <gresource prefix="/io/github/zhaob1n/Mirai/icons/hicolor/scalable/actions">'
  for n in $names; do
    f=$(find "$src/Adwaita/symbolic" -name "$n.svg" | head -1)
    [ -n "$f" ] || { echo "update-icons.sh: $n not in adwaita-icon-theme" >&2; exit 1; }
    cp "$f" "$here/icons/"
    echo "    <file alias=\"$n.svg\">icons/$n.svg</file>"
  done
  echo '  </gresource>'
  echo '</gresources>'
} > "$here/icons.gresource.xml"
echo "$(echo "$names" | wc -l) icons"
